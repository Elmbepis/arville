2.	Conjunction
</u>$black
<br/><br/>
The conjunction of two propositions is a statement that is true only when both of the propositions are true. Conjunction is symbolized by the 'and' symbol, represented by the '&#8743;' operator. 
For example, the conjunction of the propositions \"it is raining\" and \"the streets are wet\" is \"it is raining and the streets are wet.\"
