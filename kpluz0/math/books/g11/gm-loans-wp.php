Amortization refers to the process of paying off a loan over time through regular payments. Each payment consists of both principal and interest. 

The principal is the amount of the loan that is being paid off, while the interest is the cost of borrowing the money. 

As the loan is paid off, the amount of the payments that goes towards the principal increases and the amount that goes towards the interest decreases.

