Markdown
@nblue
<br/><br/>
Markdown refers to the reduction or decrease in the selling price of a product or service from its original or previously established price. This reduction in price is often implemented for various reasons, such as to stimulate sales, 
clear out excess inventory, attract customers during promotional events, or respond to shifts in market conditions.
<br/><br/>
Markdown differs from discount in the sense that markdowns generally provide everyone with the ability to purchase goods at a reduced rate. 
Discounts, however, may be available to just a select group of shoppers, such as students or loyalty program members. 
<br/><br/>
While both markdowns and discounts may encourage customers to buy items, discounts may create a stronger emotional response and cause customers to feel valued or special.
<br/><br/>
