In propositional logic, a conditional proposition is a statement of the form \"if p then q,\" where p and q are propositions. The statement is read as \"p implies q\" or \"q is a necessary consequence of p.\" 
<br/><br/>
Conditional propositions are also known as implication and are represented by the symbol '&#8594;' .
<br/><br/>
There are different forms of conditional propositions, each with its own characteristics and implications.
<br/><br/>
