Personal Loans
</i>$black<br/><br/>
Personal loans are the most common type of consumer loan. These loans are typically used to consolidate debt, pay for unexpected expenses, or fund major purchases such as home renovations or weddings. 
Personal loans are unsecured and can be either fixed or variable rate. Fixed-rate personal loans have a set interest rate for the life of the loan, while variable rate loans have an interest rate that can fluctuate over time.
<br/><br/>$pink<i>
Auto Loans
</i>$black<br/><br/>
Auto loans are specifically designed to help consumers purchase a car or other vehicle. Auto loans are secured by the vehicle, meaning that if the borrower defaults on the loan, the lender can repossess the car. 
Auto loans can be either new or used and can have either fixed or variable interest rates.
<br/><br/>$pink<i>
Student Loans
</i>$black<br/><br/>
Student loans are used to fund higher education expenses, including tuition, room and board, textbooks, and other education-related costs. Student loans can be either federal or private, 
and can be either subsidized or unsubsidized. Subsidized student loans do not accrue interest while the borrower is in school, while unsubsidized loans begin accruing interest immediately.
<br/><br/>$pink<i>
Credit Cards
</i>$black<br/><br/>
While technically not a loan, credit cards function much like a loan in that they allow consumers to borrow money to make purchases. Credit cards are unsecured and can have either a fixed or variable interest rate. 
Unlike other types of loans, credit cards allow consumers to borrow money repeatedly up to their credit limit, and to pay it back over time.
