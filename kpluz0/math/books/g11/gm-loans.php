Lines of Credit 
</i>$black<br/><br/>
A line of credit is a type of loan that provides a company with a pre-approved credit limit. This type of loan is often used to cover short-term expenses, such as inventory purchases or unexpected cash flow gaps. 
The borrower only pays interest on the amount they use, and the credit line can be used repeatedly as long as the borrower stays within the credit limit. Lines of credit can be secured or unsecured and may have a variable or fixed interest rate.
