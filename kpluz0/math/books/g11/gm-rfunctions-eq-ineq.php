Rational Function
@nblue
<br/><br/> 
A rational function is a function of the form f(x) = (P(x))/(Q(x)), where P(x) and Q(x) are polynomials and Q(x) is not equal to zero. 
<br/><br/>
The domain of a rational function is all real numbers except for the zeroes of Q(x), which are known as vertical asymptotes. 
<br/><br/>
The graph of a rational function is a single smooth curve that approaches but does not touch the vertical asymptotes.
