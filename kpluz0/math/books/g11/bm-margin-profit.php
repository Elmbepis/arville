<br/><br/>
Profit represents the financial gain that is realized when total revenue from sales surpasses the total costs incurred to produce, distribute, and sell goods or services. 
It differs from margin in the sense that it is expressed as a numerical amount in currency, not as a percentage.
<br/><br/>
