A deferred annuity is a type of annuity contract in which the investor makes a series of payments to the annuity provider, but the payments are not converted into income payments until a later date. 
The present value (PV) of a deferred annuity is the current value of the future income payments that the investor will receive, 
taking into account the time value of money. The period of deferral, also known as the accumulation period, is the length of time between the initial investment and the start of the income payments.
To calculate the present value and period of deferral of a deferred annuity, you will need the following information:
<br/><br/>
1.	The annuity payment: The fixed amount that the investor will receive each period.
<br/><br/>
2.	The interest rate: The rate at which the investment will grow over time.
<br/><br/>
3.	The number of periods: The number of periods over which the investment will grow.
<br/><br/>
4.	The number of income payments: The number of payments that the investor will receive once the income payments begin.
<br/><br/>
