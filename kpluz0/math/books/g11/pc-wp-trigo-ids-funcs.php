1. A construction worker needs to find the height of a building using a ladder and a protractor. The ladder is placed at a 30 degree angle from the base of the building, and the worker measures the angle formed by the top of the building and the ladder to be 60 degrees. Using the trigonometric identities, what is the height of the building?
Solution: We can use the tangent identity to find the height of the building:
tan(60) = height / base
height = base * tan(60)
height = base * &#8730;3/3
Since we know that the ladder forms a 30 degree angle with the base, we can use the sine identity to find the length of the ladder (base):
sin(30) = base / height
base = height * sin(30)
base = height * 1/2
So we can substitute this value of base in the first equation:
height = (height * 1/2) * &#8730;3/3
height = (height * &#8730;3/6)
height = height * &#8730;3/6
therefore height = height &#8730;3/6

2. A pilot needs to fly a plane at an altitude of 8,000 feet and a distance of 10 miles from a radio tower. The pilot measures the angle formed by the ground and the line of sight to the tower to be 45 degrees. Using trigonometric identities, what is the distance of the plane from the tower?
Solution: We can use the tangent identity to find the distance of the plane from the tower:
tan(45) = opposite / adjacent
distance = altitude / tan(45)
distance = 8,000 / 1
distance = 8,000 feet

