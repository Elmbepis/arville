Angles are measured in degrees (&deg;). 
For example, a right angle has a measurement of 90&deg;. 
Thus, perpendicular lines or line segments intersect at an angle of 90&deg;.
<br/><br/>
You can use an instrument called a protractor to measure an angle. 
To do so, you first need to place the protractor's midpoint on the vertex of the angle such that the protractor's zero line is aligned with one side of the angle. 
<br/><br/>
You then find the protractor's line that aligns with the other side of the angle. 
The number of degrees corresponding to that line is the measurement of the angle.
