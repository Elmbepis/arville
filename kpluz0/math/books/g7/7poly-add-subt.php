In algebra, we deal a lot with numbers and variables.  A variable is a symbol such as 'x' and 'y' that represents a number that is not known yet. 
<br/><br/>
Algebraic terms, or simply 'terms', are items that are added or subtracted in an algebraic expression.  For example, in the expression '2x + 4y + 5z', the terms are 2x, 4y, and 5z.
<br/><br/>
A term has a numerical factor and a literal factor. The numerical factor is a specific number that multiplies the literal factor.  The literal factor consists of one or more variables contained in the term. The numerical factor is also often referred to as the 'numerical coefficient'.
<br/><br/>
For example, the numerical coefficient of the term '5xy' is '5' while its literal factor is 'xy'.  It simply means 5 times 'xy'.
<br/><br/>
A term that contains no variables and is therefore just a number is called a 'constant'.
<br/><br/>
Like terms are terms that contain exactly the same variables raised to exactly the same power.  The order in which the variables appear does not matter, as long as the exponents are the same.
<br/><br/>
For example, 4x<sup>2</sup>y<sup>2</sup> and 7y<sup>2</sup>x<sup>2</sup> are like terms, since they both contain x<sup>2</sup> and y<sup>2</sup>, and no more or less than that. 
<br/><br/>
Note that like terms can have different numerical coefficients.  Only like terms can be added or subtracted in an algebraic expression.  When like terms are added or subtracted, only the numerical coefficients change.  The literal factor of terms stay the same.
<br/><br/>
For example, 15abc + 4abc - 6abc = 13abc.  As we can see from this example, the mathematical operations were only performed on the numerical coefficients, i.e., (15 + 4 - 6)abc = 13 abc.
