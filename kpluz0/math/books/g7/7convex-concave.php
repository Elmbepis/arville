Angles that are greater than 180&deg; are called reflex angles. Vertices at the reflex angles of a concave polygon appear to have been pushed inward the polygon's body.
<br/><br/>
Each reflex angle also creates a 'cave' outside the polygon, hence the name 'concave'.
