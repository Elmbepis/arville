A polygon is a figure formed by fitting together line segments end to end.
<br/><br/>
Let P<sub>1</sub>, P<sub>2</sub>, ..., P<sub>n</sub> be a sequence of n distinct points in a plane, with n &ge; 3.  
Suppose that the n segments formed with these points as endpoints have the following properties:
<br/><br/>
1. No two of the segments intersect except at their endpoints.
<br/><br/>
2. No two segments with a common endpoint are collinear.
<br/><br/>
Then the union of the n segments is called a polygon.
<br/><br/>
A polygon is a closed figure, which means its sides connect to form a loop with no gaps anywhere.
