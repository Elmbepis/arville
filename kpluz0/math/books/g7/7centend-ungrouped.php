@nblue
<br/><br/>
The mode of a set of data is simply the value that appears most frequently in the set.
<br/><br/>
If two or more values appear most frequently with the same frequency, then each of them is a mode. 
<br/><br/>
The downside to using the mode as a measure of central tendency is that a set of data may have no mode, or it may have more than one mode. 
However, the same set of data will have only one mean and only one median.
<br/><br/>
If a data set has only one value that occurs most often, then it has only one mode and the set is said to be unimodal.
<br/><br/>
On the other hand, a data set that has two values that occur with the same greatest frequency is referred to as bimodal.
<br/><br/>
When a set of data has more than two values that occur with the same greatest frequency, the set is called multimodal.
