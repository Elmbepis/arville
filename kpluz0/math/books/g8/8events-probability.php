If you toss a coin, there are 2 possible outcomes: heads or tails.
If you roll a die, there are 6 possible outcomes: 1, 2, 3, 4, 5, or 6.
<br/><br/>
In math, actions like tossing a coin and rolling the die are called experiments.
If the outcome of an experiment is not always the same when it is repeated (such as when you toss a coin or roll a die), then it is said to be a random experiment.
<br/><br/>
The set of all possible outcomes of a random experiment is called a sample space.
Any subset of the sample space is called an event.
<br/><br/>
