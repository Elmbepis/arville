The parallel sides are equal in length and opposite each other.
<br/><br/>
If a parallelogram has four right angles, then it is a rectangle.
A square is a special type of rectangle whose sides are all equal.
<br/><br/>
A rhombus is any parallelogram with equal sides.
A typical rhombus looks like a square that's leaning to one side.
<br/><br/>
Note, however, that a square is also a rhombus.
It is a special rhombus with four right angles.
<br/><br/>
A rhombus that is not a square has two opposite equal acute angles and two opposite equal obtuse angles.
<br/><br/>
If a parallelogram has no right angles and its sides are not all equal, then it is called a rhomboid.
