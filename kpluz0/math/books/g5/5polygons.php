Polygons are classified as either regular or irregular polygons.
A regular polygon is a polygon that has equal sides and equal angles. 
<br/><br/>
A figure whose sides are all equal is said to be equilateral.
A figure whose angles are all equal is said to be equiangular.
A regular polygon is therefore both equilateral and equiangular.
<br/><br/>
An irregular polygon, on the other hand, is therefore one that doesn't have equal sides nor equal angles.
