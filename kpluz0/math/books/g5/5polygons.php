Polygons may also be classified as either 'concave' or 'convex'. 
<br/><br/>
A concave polygon is a polygon with at least one interior angle greater than 180 degrees.
An interior angle is an angle formed inside the polygon by adjacent sides.
<br/><br/>
A convex polygon doesn't have an interior angle that's more than 180 degrees.
<br/><br/>
Distinguishing concave polygons from convex ones may be confusing at first.
However, it becomes easier as you get used to it.
<br/><br/>
