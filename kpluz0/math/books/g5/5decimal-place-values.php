Just like whole numbers, decimal numbers are made up of digits.
Each of these digits has its own place value.
<br/><br/>
We are already familiar with the place values of digits to the left of the decimal point of a decimal number.
These place values are just the same as those of whole numbers.
<br/><br/>
In this lesson, we will learn the place values of digits to the right of the decimal point. 
<br/><br/>
The digit immediately to the right of the decimal point has a place value of tenths.  
The digit to the right of the 'tenths' digit has a place value of hundredths.
<br/><br/>
For example, in the decimal number 1.24, the digit '1' has a place value of 'ones', the digit '2' has a place value of tenths, and the digit '4' has a place value of hundredths.
<br/><br/>
The value of the decimal number itself is the sum of the place values of its digits.
Using our example above to show this, 1 + 2/10 + 4/100 = 1 + 0.2 + 0.04 = 1.24.
<br/><br/>
As in whole numbers, the place value of each digit of a decimal number decreases as the digit goes farther to the right.
<br/><br/>
Here are the first six place values that we see to the right of the decimal point in decimal numbers: tenths, hundredths, thousandths, ten-thousandths, hundred-thousandths,
millionths.
