<br/><br/>
The amount equal to a certain percent of a number is called the percentage. 
The percent itself is called the rate.
The number that you are taking a percentage of is called the base.  
<br/><br/>
We've already learned that 50% is equal to 1/2, so we know that 20 is 50% of 40. 
In this example, the base is 40, the rate is 50%, and the percentage is 20.
<br/><br/>
To find the percentage (P) of a base (B) given the rate (R), we simply need to multiply the base by the equivalent fraction or decimal number of the rate.
<br/><br/>
This is the formula: <font color='#800080'><b>P = B x R</b><font color='#000000'>.
<br/><br/>
For example, to get 30% of 70, we can either multiply 70 by 3/10 (that's 30/100) or by 0.30.
Thus, 30% of 70 = 70 x 3/10 = 21.
<br/><br/>
To find the rate (R) given the base (B) and the percentage (P), we simply need to divide the percentage by the base and express the answer in percent.
<br/><br/>
This is the formula: <font color='#800080'><b>R = P / B</b><font color='#000000'>.
<br/><br/>
For example, if the base is 40 and the percentage is 20, then the rate R = P/B = 20/40 = 0.5 = 50%.
<br/><br/>
