@vio<u>Sphere</u>@nvio
<br/><br/>
A sphere is a solid figure that is shaped like a ball. 
Every point on its surface is equidistant from its center. 
<br/><br/>
This means that the distance between the center of a sphere and any point on its surface is the same. 
This distance is called the radius of the sphere.
<br/><br/>
The diameter of a sphere is two times its radius. 
This is the length of any line segment that passes through the center and whose ends lie on the surface of the sphere. 
<br/><br/>
Objects that have the shape of a sphere are said to be spherical.
Basketballs, marbles, globes, and large heavenly bodies such as planets and moons are examples of spherical objects.
