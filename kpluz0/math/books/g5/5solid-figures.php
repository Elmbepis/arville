@vio<u>Pyramid</u>@nvio
<br/><br/>
A pyramid is a solid figure that, like a cone, has a base that narrows to an apex.
Unlike a cone, the base of a pyramid is a polygon, not a circle. 
<br/><br/>
The sides of a pyramid are triangular.
The height of a pyramid is the distance between the center of its base and its apex.
<br/><br/>
The pyramids of Egypt are obvious examples of pyramid-shaped objects. 
Other examples of objects that sometimes come in the shape of a pyramid are rooftops and tents.
