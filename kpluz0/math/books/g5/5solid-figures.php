Solid figures are figures that have three dimensions: length, width, and height. 
As such, they are also called three-dimensional or 3-D figures.
<br/><br/>
Since the world is three-dimensional, solid figures are everywhere around us. 
Below are the basic solid figures commonly studied in math.
