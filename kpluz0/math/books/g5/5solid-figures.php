@vio<u>Prism</u>@nvio
<br/><br/>
A prism is a solid figure that consists of two parallel end faces and side faces that are parallelograms. 
A parallelogram is a shape with four straight sides, each of which is parallel to the opposite side.
<br/><br/>
Also, the two end faces of a prism must be polygons of the same size and shape. 
A polygon is a shape with straight sides. 
