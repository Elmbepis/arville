<br/>
A rectangular prism is a prism with six faces, all of which are rectangles. 
A rectangular prism looks like a rectangular box.
<br/><br/>
We encounter a lot of rectangluar prisms every day. 
Cereal boxes, shoeboxes, books, cabinets, bed mattresses, ovens, aquariums, and many other common objects often come in the form of a rectangular prism.
<br/><br/>
Squares are rectangles with equal sides.
As such, cubes are just rectangular prisms whose six faces are all squares of the same size.
<br/><br/>
The faces of a prism meet at line segments called edges. 
The edges of a prism meet at points called vertices (singular: vertex). 
