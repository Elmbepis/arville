@vio<u>Cylinder</u>@nvio
<br/><br/>
A cylinder is a solid figure that has two circular end faces, called bases, that are connected together by a curved side. 
The shortest distance between the bases of a cylinder is called its height.
<br/><br/>
The radius of a cylinder is the shortest distance between its center and its edge.
Its diameter is twice its radius.
<br/><br/>
Objects shaped like a cylinder are said to be cylindrical.
Common objects that are cylindrical include tubes, pipes, candles, and cans. 
