@vio<u>Cone</u>@nvio
<br/><br/>
A cone is a solid figure that has one circular end face, called its base, that narrows to a point at the opposite end.
This point is called its apex or vertex.
<br/><br/>
The height of a cone is the distance between the center of its base and its apex.
<br/><br/>
The radius of a cone is the shortest distance between the center and the edge of its base.
Its diameter is twice its radius.
<br/><br/>
Objects that have the shape of a cone are said to be conical.  
<br/><br/>
Examples of conical objects include ice cream cones, New Year horns, traffic cones, teepees, and Asian conical hats.
