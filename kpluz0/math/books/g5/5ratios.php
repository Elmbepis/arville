A ratio is a comparison of two numbers that shows how many times one number is of the other number.  
<br/><br/>
The most common way of writing a ratio is to write the numbers separated by a colon like this:  4:9.  
In this example, we are saying that the ratio is 4 is to 9.
<br/><br/>
Ratios are important in expressing relationships between quantities.  
<br/><br/>
For example, if we say that the ratio of cupcakes to children at a party is 3 is to 1, or  3:1, we are actually saying that each child in the party will get 3 cupcakes.  
So if there are 8 children, there are 24 cupcakes.  
