<br/><br/>
The ratio between any two numbers may be further simplified as long as they have one or more common factors. 
<br/><br/>
To do this, we simply need to divide both numbers by their greatest common factor (GCF), and rewrite the ratio in the same order.
<br/><br/>
Say, for example, that the ratio of computers to students in a school is 12:30.
The GCF of 12 and 30 is 6. 
Dividing both numbers by 6, we can express the ratio 12:30 as 2:5.
<br/><br/>
The original ratio tells us that 12 computers are being used by 30 students. 
It also means that every two computers are shared by 5 students, as shown by the simplified ratio. 
