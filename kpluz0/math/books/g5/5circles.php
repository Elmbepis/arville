Parts of a Circle
@nblue
<br/>
A circle has several parts that we need to be familiar with.
<br/><br/>
We already know that a circle's center is the fixed point from which all points on a circle are the same distance.
<br/><br/>
A line segment connecting a circle's center to a point on the circle is also called a radius.
<br/><br/>
A line segment that starts on one point on a circle, passes through the circle's center, and ends on another point at the other side is called a diameter.
Note that the diameter is twice as long as the radius.
<br/><br/>
Any line segment that starts and ends on points on a circle is called a chord. 
A diameter is therefore a chord that passes through the center.
<br/><br/>
The distance around a circle is called its circumference. 
If we use a string to form a perfect circle, the length of the string is the circumference of this circle. 
A portion of the circumference is called an arc.
<br/><br/>
