Say a cat walks around a tree in such a way that it is always the same distance away from this tree. 
The path that the cat would complete when it returns to its starting point would be in the shape of a circle. 
<br/><br/>
A circle is the set of all points on a plane that are at the same distance from a fixed point. 
This fixed point is the center of the circle.
<br/><br/>
The distance from any point on a circle to its center is called its radius. 
The radius is often denoted by the letter 'r'.
