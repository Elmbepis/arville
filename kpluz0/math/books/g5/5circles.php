<br/>
A line that intersects a circle at two points is called a secant. 
It is similar to a chord, except that it is a line so it does not end.
<br/><br/>
A line that touches a circle at exactly one point is called a tangent. 
Note that a tangent does not intersect the circle; it merely touches the edge of the circle. 
<br/><br/>
The point where a tangent touches a circle is called the point of tangency.
The radius of the circle at the point of tangency is perpendicular to the tangent line.
