A multiple of a number is a product of that number multiplied by an integer. 
For example, 12 is a multiple of 4 because if 4 is multiplied by 3 (an integer), you will get 12. 
<br/><br/>  
The first five multiples of 4 are: 8 (because 8=4x2), 12 (4x3), 16 (4x4), 20 (4x5), and 24 (4x6). 
The list of multiples of a number never ends.
