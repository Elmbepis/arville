The term 'percent' means 'per 100'.  
<br/><br/>
Thus, 'percent' is used to indicate how many parts there are for every 100 parts.  
The symbol for percent is '%', so 50 percent is written as 50%.
<br/><br/>
100% means 100 parts out of 100 parts, or 1 whole.  
That's why 100% equals 1.  
<br/><br/>
Anything less than 100% is therefore less than 1. 
Anything more than 100% is therefore greater than 1.
<br/><br/>
When you say you have 1% of something, you are saying that you have 1 part out of 100 parts of that 'something', or 1/100.  
The equivalent fraction of 1% is therefore 1/100. 
<br/><br/>
To convert a percent number into a fraction, we simply need to use it as the numerator (without a percent symbol) of the fraction and use 100 as the fraction's denominator. 
For example, 17% is equal to 17/100 while 50% is equal to 50/100 or 1/2. 
<br/><br/>
We can also get the equivalent decimal number of a percent number.
One percent equals 1/100, which is 0.01 in decimal form. 
<br/><br/>
To convert a percent number into a decimal number, we simply need to multiply it by 0.01 and drop the percent symbol. 
For example, 25% = 25 x 0.01 = 0.25. 
<br/><br/>
If you haven't noticed, moving the decimal point of a percent number 2 places to the left and dropping the percent symbol turns it into a decimal number. 
