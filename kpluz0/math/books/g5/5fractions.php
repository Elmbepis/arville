Types of Fractions
@nblue
<br/> 
There are three types of fractions: proper, improper, and mixed fractions. 
<br/><br/>
A proper fraction is a fraction whose numerator is smaller than its denominator. 
Examples of proper fractions are: 1/7, 4/9, and 7/12. 
<br/><br/>
All proper fractions are less than the whole, or less than 1 in absolute value.
<br/><br/>
An improper fraction is a fraction whose numerator is larger than its denominator. 
Examples of proper fractions are: 4/3, 9/5, and 13/8.
<br/><br/>
All improper fractions are more than the whole, or greater than 1 in absolute value.
<br/><br/>
A mixed fraction is a fraction that is made up of a whole number and a proper fraction. 
An example of a mixed fraction is one and one-half, or 1 1/2.
Two and three-fifths, or 2 3/5, is another example.
