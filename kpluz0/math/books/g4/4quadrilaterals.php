$vio<u>Trapezoid</u>$black
<br/><br/>
A quadrilateral with only one pair of parallel sides is called a trapezoid.
Its parallel sides are called bases while its non-parallel sides are called legs.
<br/><br/>
Since the legs of a trapezoid are not parallel, its bases are never equal in length.
<br/><br/>
However, its two legs could be equal. 
A trapezoid whose legs are equal is called an isosceles trapezoid.
<br/><br/>
By the way, some books define a trapezoid as a quadrilateral with at least one pair of parallel sides.
If we use this definition, then all parallelograms are trapezoids!
