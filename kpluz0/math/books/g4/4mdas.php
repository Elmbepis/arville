In math, the order in which operations are undertaken matters. 
Perfoming a set of operations in an incorrect order can result in errors in the calculation. 
<br/><br/>
For example, your answer to 2 + 3 x 5 will be 25 if you add 2 and 3 first before multiplying the result by 5. 
<br/><br/>
The correct order is to multiply 3 and 5 first before adding 2 to their product, which will give an answer of 17.  
<br/><br/>
Thus, when working on a math expression with several operations, multiplication and division (MD) must always be done first before addition and subtraction (AS). 
<br/><br/>
The letters shown in parentheses above form the acronym 'MDAS', which reminds us to do multiplication and division first before addition and subtraction. 
