In the last lesson, we learned how to multiply three-digit numbers by two-digit numbers.
In this lesson, we will learn how to divide three- to four-digit numbers by one- to two-digit numbers.
<br/><br/>
If you divide a product of two factors by one of the factors, you will get the other factor. 
For example, 12 is the product of 4 and 3. 
If we divide 12 by 3, we would get 4.
<br/><br/>
Thus, division is basically the reverse of multiplication. 
As such, your mastery of the multiplication table will also help you in division. 
<br/><br/>
In division, the number being divided is called the dividend while the number that divides it is called the divisor.
The answer you get from division is called the quotient.
<br/><br/>
