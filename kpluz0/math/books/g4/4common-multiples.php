Most numbers are multiples of several different numbers. 
For example, 24 is a multiple of 1, 2, 3, 4, 6, 12, 8, and 24. 
<br/><br/> 
A number that is a multiple of two other numbers is called a 'common multiple' of those two numbers. 
For example, 12 is common multiple of 3 and 4 while 35 is a common multiple of 5 and 7.
