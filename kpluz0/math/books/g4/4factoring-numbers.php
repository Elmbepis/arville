Factors are numbers that are multiplied together to get another number.  
For example 5 and 7 are factors of 35 because 5 x 7 = 35.  
<br/><br/>   
A number is always divisible by its factors.  
Also, a number is always a multiple of its factors.
<br/><br/>   
Factoring a number, or factorization, means getting all the factors of a number, or finding all the numbers that the original number is divisible by.  
<br/><br/>   
For example, you can use factorization to know that the factors of 12 are as follows:  1, 2, 3, 4, 6, and 12. The number 12 is divisible by all of these numbers.
