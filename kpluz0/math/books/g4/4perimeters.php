<br/><br/>
The boundary of a circle is called its circumference.
<br/><br/>
The formula for the circumference of a circle is:
<br/><br/>
$red<b>C = &pi; x D</b>$black, or<br/>
$red<b>C = 3.14 x D</b>$black
<br/><br/>
where 'C' is the circumference, '&pi;' is a special number that's always equal to around 3.14, and 'D' is the diameter of the circle.
<br/><br/>
The diameter of a circle is a line segment that passes through its center and whose endpoints lie on the circumference. 
<br/><br/>
The diameter of a circle is twice the radius of a circle so sometimes you'd see a formula for the circumference that looks like this:
<br/><br/>
$red<b>C = 2 x &pi; x R</b>$black, or<br/>
$red<b>C = 6.28 x R</b>$black where R is the radius.
<br/><br/>
