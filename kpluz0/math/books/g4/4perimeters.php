A plane figure is a flat, closed figure that lies entirely on one plane. 
It has only two dimensions: length and width. 
It is therefore a two-dimensional shape.
<br/><br/>
Since a plane figure is closed, it is completely surrounded by a boundary.
The total length of the boundary of a plane figure is called its perimeter.
