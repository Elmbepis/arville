Numbers from 21 to 99 must be hyphenated. 
This means that the word for the 'tens' digit must be separated from the word for 'ones' digit with a hyphen. 
Thus, we write 47 as 'forty-seven' and 85 as 'eighty-five'. 
<br/><br/>
Don't use commas when writing large numbers in words.
Thus, 1,965 must be written as one thousand nine hundred sixty-five.
<br/><br/>
As a last reminder, we must be careful with our spelling. 
We definitely don't want to write 'sixteen' as 'sixty'.
