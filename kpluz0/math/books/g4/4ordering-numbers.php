In the last lesson, we learned how to compare numbers with up to six digits. 
In this lesson, we will learn how to arrange them in increasing and decreasing orders. 
<br/><br/>
To arrange a list of numbers, we must compare each number with the other numbers. 
We then make a new list wherein the numbers follow either an increasing or decreasing order.  
<br/><br/>
When arranging numbers in increasing order, we must list them from the one with the least value to the one with the greatest value. 
Each number on the list must be greater than the one it followed. 
<br/><br/>
For example, if we arrange 236, 179, 728, and 547 in increasing order, we would have this list: 179, 236, 547, 728. 
<br/><br/>
When arranging numbers in decreasing order, we must list them from the one with the greatest value to the one with the least value. 
Each number on the list must be less than the one it followed. 
<br/><br/>
For example, if we arrange 342, 612, 193, and 857 in decreasing order, we would have this list: 857, 612, 342, 193. 
