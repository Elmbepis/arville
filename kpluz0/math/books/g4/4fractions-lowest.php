<br/><br/>
A fraction in lowest terms means that it is in its simplest form.
Its numerator and denominator are no longer divisible by any whole number, and are therefore at their lowest possible values. 
<br/><br/>
Reducing fractions into lowest terms simplifies calculations.  
It is therefore a skill that every math student must learn.
<br/><br/>
It is not difficult to reduce fractions into lowest terms. 
You simply need to divide both the numerator and the denominator by their common factors.
<br/><br/>
