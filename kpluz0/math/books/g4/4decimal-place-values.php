Just like whole numbers, decimal numbers are made up of digits.
Each of these digits has its own place value. 
<br/><br/>
We are already familiar with the place values of digits to the left of the decimal point of a decimal number.
These place values are just the same as those of whole numbers.
<br/><br/>
In this lesson, we will learn the place values of digits to the right of the decimal point. 
<br/><br/>
We know that in any whole number, the place value of a digit is always 10 times the place value of the digit on its right. 
This is also true for decimal numbers.
<br/><br/>
The digit immediately to the right of the decimal point has a place value of tenths.  
The digit to the right of the 'tenths' digit has a place value of hundredths.
<br/><br/>
The value of a tenth (1/10) is ten times the value of a hundredth (1/100). 
<br/><br/>
Now, let's look at the decimal number <font color='#800080'><b>1.24<font color='#000000'></b>. 
The digit '1' has a place value of 'ones', the digit '2' has a place value of tenths, and the digit '4' has a place value of hundredths.
<br/><br/>
The value of the decimal number itself is the sum of the values of its digits.
<br/><br/>
Let's use our example above to show this. 
The sum of the values of the digits of <font color='#800080'><b>1.24<font color='#000000'></b> is:<br/><br/>
1 + 2 x (1/10) + 4 x (1/100)<br/> 
= 1 + 2/10 + 4/100<br/> 
= 1 + 0.2 + 0.04<br/>
= <font color='#800080'><b>1.24<font color='#000000'></b>.
<br/><br/>
As in whole numbers, the place value of each digit of a decimal number decreases as the digit goes farther to the right.
<br/><br/>
Here are the first five place values that we see to the right of the decimal point in decimal numbers: tenths, hundredths, thousandths, ten-thousandths, hundred-thousandths.
