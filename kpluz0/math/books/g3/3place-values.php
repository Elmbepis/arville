The numerals that make up a number are called 'digits'.  For example, the digits of the number 657 are '6', '5', and '7'.
<br/><br/>
The position of each digit in a number tells us its value. The value of each digit in a number is called its place value. <br/><br/>
The digit in the rightmost position has a place value of ones.  The digit to its left has a place value of tens.
<br/><br/>
For example, the digit '7' of 72 is in the tens place, so its value is 70. The digit '2' is in the ones place so its value is 2. <br/><br/>
The sum of the place values of the digits is the number itself: 70 + 2 = 72.
<br/><br/>
The digit '2' of 248 is in the hundreds place. The digit '4' is in the tens place. The digit '8' is in the ones place.
<br/><br/>
The digit '5' of 5,716 is in the thousands place. 
The digit '7' is in the hundreds place. 
The digit '1' is in the tens place. 
The digit '6' is in the ones place.
<br/><br/>
Here are the first six place values that we see in numbers: ones, tens, hundreds, thousands, ten thousands, and hundred thousands.
