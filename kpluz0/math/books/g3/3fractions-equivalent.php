<br/><br/>
We can make equivalent fractions of a given fraction by multiplying or dividing both the numerator and denominator of the given fraction by the same number.
<br/><br/>
Remember, we are not changing the value of a fraction if we are multiplying both its numerator and denominator by the same number.
It's like we're just multiplying it by 1.
<br/><br/>
In our example above, we can multiply both the numerator and denominator of the first fraction, 2/4, by 2.
The equivalent fraction that we'd get is 4/8, which is the second fraction in our example.
