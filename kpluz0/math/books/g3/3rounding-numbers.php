Rounding off a number means making it simpler by making some of its rightmost digits zero. 
<br/><br/>
For example, if we want to multiply 111 by 101, we can round off the number 101 to 100. 
It would be easier to multiply 111 by 100, but you'll get an answer that is a little less than 111 times 101.
<br/><br/>
A rounded number is therefore simpler than the original number, but will give less exact results. 
<br/><br/>
We already know by now that each digit of a number has a given place value. 
We can round off a number to any place value, depending on how much simpler we want the number to be. 
<br/><br/>
Rounding off a number to the nearest thousand, for instance, will make it simpler (but less exact) than rounding it off to the nearest ten. <br/><br/>
The digit of the place value to which we want to round off a number is called the rounding digit. 
For example, if we want to round off 7863 to the nearest ten, 6 is the rounding digit. 
<br/><br/>
Below are the two basic rules for rounding off a number. 
<br/><br/>
If the number to the right of the rounding digit is less than 5 (0, 1, 2, 3, or 4), then keep the rounding digit but change all the digits to its right to zero. 
<br/><br/>
If the number to the right of the rounding digit is 5 or above (5, 6, 7, 8, or 9), then add one to the rounding digit and change all the digits to its right to zero. 
<br/><br/>
As an example, let's round off 6728 to the nearest hundred.
For this place value, the rounding digit is 7 and the number to its right is 2.
Since 2 is less than 5, we should apply the first rule and round 6728 to 6700. 
<br/><br/>
Say that this time, we want to round off 6728 to the nearest ten.
For this place value, the rounding digit is 2 and the number to its right is 8.
Since 8 is greater than 5, we should apply the second rule and round 6728 to 6730. 
<br/><br/>
Let us now look at more examples of how to round off numbers to different place values.
