One way to visualize large numbers is to use little squares. 
We can group 10 little squares into one column, forming what we may call a 'long'. <br/><br/>
If we put 10 'longs' next to each other, we would form a square that we could call a 'flat'. 
Each flat has 100 squares because there are 10 squares per long. 
<br/><br/>
Lastly, we can group 10 flats together to form a cube. 
Each cube would have 1,000 squares since there are 100 squares in each flat. 
