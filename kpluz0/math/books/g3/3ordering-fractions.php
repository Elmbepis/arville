In the last lesson, we learned how to compare dissimilar fractions. 
In this lesson, we will learn how to arrange them in increasing and decreasing orders. 
<br/><br/>
To arrange a list of fractions, we must compare the value of each fraction with those of the other fractions. 
We then make a new list wherein the fractions are in either increasing or decreasing order.
<br/><br/>
When arranging fractions in increasing order, we must list them from the one with the least value to the one with the greatest value. 
<br/><br/>
For example, if we arrange 1/2, 6/7, 2/3, and 1/3 in increasing order, we would have this list: 1/3, 1/2, 2/3, 6/7. 
<br/><br/>
When arranging fractions in decreasing order, we must list them from the one with the greatest value to the one with the least value. 
<br/><br/>
For example, if we arrange 1/4, 1/9, 4/7, and 8/9 in decreasing order, we would have this list: 8/9, 4/7, 1/4, 1/9. 
