If 24 cupcakes were given to 8 children and each child got the same number of cupcakes, how many cupcakes did each child get? 
<br/><br/>
To answer this question quickly, we need to do a math operation called division. 
Division in math simply means splitting a quantity into smaller and equal groups. 
<br/><br/>
The number that we are dividing is called the dividend. 
The number dividing it is called the divisor. 
The result of division is called the quotient.
<br/><br/>
In our question above, we need to divide the total number of cupcakes, 24, by the total number of children, 8.
The dividend is therefore 24 and the divisor is 8. 
<br/><br/>
So how do we divide the cupcakes? 
We could give each child one cupcake each at first, but there would be some cupcakes left.
We could continue giving each child one cupcake until there's none left. 
<br/><br/>
The quotient is the number of cupcakes that each child would be holding after all the cupcakes had been given away.
<br/><br/>
