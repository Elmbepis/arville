If their sum is less than 10, just write their sum below them under the line. 
<br/><br/>
If their sum is greater than 10, then you need to regroup their sum.
Regrouping means separating the 'tens' and 'ones' digits of the sum.
<br/><br/>
For example, if the sum of the 'ones' digits is 17, then you need to regroup this into 10 and 7. 
Write the '7' below the 'ones' digits of the addends under the line.
<br/><br/>
The '10', on the other hand, will be added to the 'tens' digits of the addends. 
We need to transfer this to the 'tens' column of the addends not as 10, but as 1 since the place value in that column is already 10. 
