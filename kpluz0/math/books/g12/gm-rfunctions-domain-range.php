The domain of a rational function is the set of all x-values for which the function is defined. 
The range of a rational function is the set of all y-values that the function can take on. 
<br/><br/>
Finding the domain and range of a rational function requires understanding the behavior of the function and the restrictions on the x-values.
<br/><br/>
The domain of a rational function f(x) = (P(x))/(Q(x)) is all real numbers except for the values of x that make the denominator Q(x) equal to zero. 
These values of x are known as vertical asymptotes. 
<br/><br/>
In other words, the domain of a rational function is all real numbers except for the zeroes of the denominator.
<br/><br/>
The range of a rational function is more complex to find. In general, the range of a rational function is the set of all real numbers, but the graph of the function can have a hole if the numerator and the denominator share a common zero. 
<br/><br/>
This zero will be a point in the graph where the function is not defined.
