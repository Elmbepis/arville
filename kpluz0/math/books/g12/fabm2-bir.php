<br/><br/>$vio<u> 
1. Determine the appropriate BIR form.
</u>$black<br/><br/>
Identify the correct BIR form that corresponds to your tax situation. For individuals earning purely compensation income, BIR Form 1700 is used.
For self-employed individuals, BIR Form 1701 is used.
<br/><br/>$vio<u> 
2. Gather income documents.
</u>$black<br/><br/>
Collect all the necessary income documents for the taxable year, including payslips, BIR Form 2316 (Certificate of Compensation Payment/Tax Withheld), 1099 forms for freelancers, business income statements, and any other relevant documents showing your earnings.
<br/><br/>$vio<u> 
3. Calculate the gross income.
</u>$black<br/><br/>
Sum up all your income from various sources to arrive at your total gross income. This includes salaries, business income, rental income, interest, dividends, and any other taxable earnings.
<br/><br/>$vio<u> 
4. Determine the allowable deductions.
</u>$black<br/><br/>
Identify the deductions you are eligible to claim based on your situation. Common deductions include contributions to government-mandated benefits (SSS, PhilHealth, Pag-IBIG), health insurance premiums, allowable expenses for self-employed individuals, 
and qualified charitable contributions.
<br/><br/>$vio<u> 
5. Compute the taxable income.
</u>$black<br/><br/>
Subtract the allowable deductions from your gross income to determine your taxable income. The resulting amount is the net taxable income that will be subject to income tax.
<br/><br/>$vio<u> 
6. Check the tax table or tax rates.
</u>$black<br/><br/>
Refer to the Philippine tax table or tax rates applicable to your taxable income range. Calculate the income tax due based on the appropriate tax rate.
<br/><br/>$vio<u> 
7. Account for tax credits<br/>and withholdings.
</u>$black<br/><br/>
Consider any tax credits, tax withheld by employers, and advance payments made during the year. These may include creditable withholding taxes (CWT) and other tax credits that can be deducted from your calculated income tax due.
<br/><br/>$vio<u> 
8. Determine the final tax due.
</u>$black<br/><br/>
After accounting for tax credits and withholdings, determine whether you have an outstanding tax balance or if you are eligible for a tax refund.
<br/><br/>$vio<u> 
9. Fill out the BIR form.
</u>$black<br/><br/>
Complete all relevant sections of the BIR Form accurately. Provide personal information, income details, deductions, tax credits, and the final computed tax due.
