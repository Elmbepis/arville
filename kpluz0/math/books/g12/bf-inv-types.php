Bonds and Fixed-<br/>Income Securities
@nblue
<br/><br/>
Bonds are a type of fixed-income security where an investor loans money to a borrower, typically a government or a corporation, for a set period of time at a predetermined interest rate. 
<br/><br/>
Bonds are often issued to raise capital and fund specific projects or operations, and can be traded on bond markets. When the bond reaches maturity, the investor receives the initial investment, known as the principal or face value, back from the borrower. 
<br/><br/>
Bonds are generally considered a less risky investment compared to stocks, as the regular interest payments and return of principal at maturity are contractual obligations of the borrower.
<br/><br/>
The recurring payment awarded to bondholders is called a coupon payment, which is usually fixed. The price of a bond can fluctuate to change the bond's yield. For example, if a bond paying 5% offers a lower yield than market opportunities, 
the bond will become cheaper to buy, leading to a higher yield.
