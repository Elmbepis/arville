Stocks or Equities
@nblue
<br/><br/>
A stock represents ownership in a public or private company. Owning a stock entitles the investor to a share of the company's profits in the form of dividends. Additionally, as the company becomes more successful, its stock value can appreciate, 
leading to potential capital gains for investors.
<br/><br/>
There are two main types of stocks: common and preferred. Common stock usually includes voting rights and participation eligibility in certain matters, while preferred stock often has first claim to dividends and must be paid before common shareholders.
<br/><br/>
Stocks can also be classified as either growth or value investments. Growth stocks are shares in companies that are still small and have yet to achieve market success. Value stocks, on the other hand, 
are shares in established companies whose stock prices may not appropriately value the company.
