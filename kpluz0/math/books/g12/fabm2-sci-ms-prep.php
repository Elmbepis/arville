2. Separation of Operating and<br/>Non-operating Activities
</u>$black<br/><br/>
The multi-step SCI separates operating activities from non-operating activities. Operating activities are those directly related to the core business operations of the company, 
such as sales of goods or services, while non-operating activities encompass items like gains or losses from the sale of assets or interest income. This separation helps stakeholders analyze the profitability of the company's primary business operations separately from other non-core activities.
