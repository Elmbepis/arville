<br/><br/>
This approach also allows investors to see how much of the company's revenues are being used to cover its costs and how much is being retained as profit. 
This information is important for investors who are trying to assess the company's financial health and make informed investment decisions.
<br/><br/>
The multiple-step approach is also useful for management because it allows them to identify areas of the business that are not performing well and make necessary changes to improve profitability. 
