The Journal
@nblue
<br/><br/>
The journal is a chronological record of financial transactions that occur within a company. It is often referred to as the \"book of original entry\" because it is where transactions are first recorded before being transferred to the general ledger. 
The journal is used to record all types of financial transactions, including sales, purchases, payments, and receipts.
<br/><br/>
Each entry in the journal includes a date, a description of the transaction, and the amounts involved. The amounts are recorded as debits and credits, and each entry must be balanced so that the total debits equal the total credits. 
This is known as double-entry bookkeeping and is a fundamental accounting concept.
<br/><br/>
The journal is used to keep track of all financial transactions in a chronological order. This makes it easier to locate and track specific transactions if there is a need for them later. 
The journal is also useful for auditing purposes because it provides a complete and accurate record of all financial transactions that have occurred.
