The General Ledger
@nblue
<br/><br/>
The general ledger is a master record of all financial transactions that have been recorded in the journal. Unlike the journal, which records transactions in chronological order, the general ledger organizes transactions by account. 
Each account has its own page in the general ledger, and all transactions related to that account are recorded on that page.
<br/><br/>
The general ledger provides a complete and detailed record of all financial transactions that have occurred within a company. It is used to track the balance of each account and to ensure that all transactions have been recorded accurately. 
The general ledger is also used to prepare financial statements, such as the balance sheet and income statement.
<br/><br/>
Each entry in the general ledger includes the date of the transaction, a description of the transaction, the amounts involved, and whether the account was debited or credited. 
The total debits and credits for each account are calculated at the end of each accounting period, and the balance of the account is updated accordingly.
