The structure of a CFS can be broken down into three main sections: the operating activities section, the investing activities section, and the financing activities section. 
Each section is presented in a specific format to make it easy for investors and other stakeholders to understand the company's cash inflows and outflows.
<br/><br/>$vio<u> 
$vio 1. Operating activities section
</u>$black<br/><br/>
The operating activities section is presented using either the direct method or the indirect method. The direct method presents the actual cash inflows and outflows of the company's operating activities, while the indirect method starts with the net income from the income statement and makes adjustments to account for non-cash items and changes in working capital. The indirect method is more commonly used due to its ease of use and practicality.
<br/><br/>$vio<u> 
$vio 2. Investing activities section
</u>$black<br/><br/>
The investing activities section shows the inflows and outflows of cash related to a company's investments in long-term assets and other companies. This section is typically presented in chronological order, starting with the cash inflows from the sale of assets or investments, followed by the cash outflows for the purchase of assets or investments.
<br/><br/>$vio<u> 
$vio 3. Financing activities section
</u>$black<br/><br/>
The financing activities section shows the inflows and outflows of cash related to a company's financing activities, such as issuing and repaying debt and issuing and repurchasing common stock. This section is typically presented in chronological order, starting with the cash inflows from borrowing and issuing stock, followed by the cash outflows for the repayment of debt and payment of dividends to shareholders.
