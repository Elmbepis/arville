1. Assets
</u>$black<br/><br/>
Assets are resources owned by a company that have monetary value, such as cash, accounts receivable, inventory, investments, property, and equipment. The assets are listed in order of liquidity, with the most liquid assets at the top.
<br/><br/>
Assets are classified as either current or non-current, depending on their expected life. Current assets are expected to be converted into cash or used up within one year, while non-current assets have a longer life expectancy.
