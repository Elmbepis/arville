2. Liabilities
</u>$black<br/><br/>
Liabilities are obligations or debts that a company owes to others, such as accounts payable, loans, and taxes owed. The liabilities are also listed in order of maturity, with the most immediate liabilities at the top.
<br/><br/>
Contingent liabilities are potential liabilities that may or may not arise depending on the outcome of a future event. Examples include lawsuits, product warranties, and environmental liabilities.
<br/><br/>
Provisions are funds that a company sets aside in its financial statements to cover future expenses or losses that are likely to occur but are not yet certain in terms of timing or amount. 
They are essentially a way for a company to plan ahead for potential future costs or liabilities.
<br/><br/>
Like assets, liabilities are classified as current or non-current, depending on when they are due to be paid. Current liabilities are expected to be paid within one year, while non-current liabilities are due in more than one year.
