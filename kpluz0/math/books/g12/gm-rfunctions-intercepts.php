Intercepts are the points at which a graph of a function crosses the x-axis or the y-axis. 
<br/><br/>
The x-intercepts of a rational function are the solutions of the equation f(x) = 0, 
while the y-intercept is the point where the function crosses the y-axis (usually represented as (0,f(0))).
<br/><br/>
To find the the x-intercept of a function, we simply need to equate f(x) to 0 and then solve for x.
<br/><br/>
To find the the y-intercept of a function, we simply need to evaluate f(0).
