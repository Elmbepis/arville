The statement of comprehensive income (SCI) is a financial statement that provides information about a company's revenues, expenses, gains, and losses over a specific period of time. 
It is also known as the income statement, statement of operations, or profit and loss statement. 
<br/><br/>
The SCI is one of the three primary financial statements that provide an overview of a company's financial health, along with the statement of financial position (SFP) and the cash flow statement.
