The statement of comprehensive income (SCI) is a financial statement that provides information about a company's revenues, expenses, gains, and losses over a specific period of time. 
<br/><br/>
For a service business, preparing an SCI using the single-step approach is a straightforward process that involves calculating the net income for the period.
<br/><br/>
The single-step approach is a method of preparing an SCI where all revenues and expenses are reported together in one line item. This approach is simpler than the multiple-step approach, 
where revenues and expenses are reported separately and gross profit is calculated before operating expenses are subtracted.
