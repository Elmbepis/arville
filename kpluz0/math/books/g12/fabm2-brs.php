Bank reconciliation is the process of comparing and matching the transactions recorded in the accounting records of a company with the transactions shown in its bank statement.
<br/><br/>
It is an essential process for any business or individual that has a bank account because it ensures that the financial records of the business or individual are accurate and complete, 
and that there are no discrepancies between the bank's records and the account holder's records. 
<br/><br/>
The bank reconciliation statement is a document that summarizes this process and provides a clear understanding of the nature of the discrepancies and how they were resolved.
<br/><br/>
The bank reconciliation statement is typically prepared at the end of a period, such as a month, and is based on the bank statement and the account holder's records. 
<br/><br/>
The statement is divided into two sections: the first section is the bank's records, and the second section is the account holder's records. The purpose of the statement is to reconcile the two records and identify any discrepancies.
<br/><br/>
The bank section of the reconciliation statement typically includes the beginning and ending balances of the account, the deposits made during the period, the checks that were cleared, the bank fees, and any interest earned on the account. 
<br/><br/>
The account holder's section typically includes the beginning and ending balances of the account, the deposits made during the period, the checks that were written, and any other transactions that were made during the period.
<br/><br/>
To prepare the bank reconciliation statement, the account holder compares the transactions recorded in their records with the transactions recorded in the bank's records. Any discrepancies are noted and investigated. 
<br/><br/>
For example, if a check written by the account holder is not reflected in the bank's records, the account holder will need to investigate the status of the check and determine why it has not been cleared.
<br/><br/>
Once the discrepancies have been identified and investigated, adjustments are made to the account holder's records to reconcile them with the bank's records. 
<br/><br/>
This might include adding in any outstanding checks or deposits that were not reflected in the bank's records, or adjusting the account holder's records to reflect any bank fees or interest earned during the period.
<br/><br/>
The bank reconciliation statement is an important tool for ensuring the accuracy and completeness of financial records. 
<br/><br/>
By identifying and resolving discrepancies between the bank's records and the account holder's records, businesses and individuals can ensure that their financial statements are accurate and reliable. 
