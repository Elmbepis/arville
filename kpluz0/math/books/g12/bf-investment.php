Dollar-Cost Averaging
@nblue
<br/><br/>
Dollar-cost averaging (DCA) is a long-term investment strategy that involves investing a fixed amount of money at regular intervals over an extended period. 
With DCA, an investor purchases a fixed dollar amount of an investment at a regular interval, regardless of whether the price of the investment is up or down.
<br/><br/>
For example, let's say an investor decides to invest $100 a month in a particular stock or mutual fund. Over the course of several months or years, they would buy a varying number of shares, depending on the current price of the investment. 
If the price is low, they would buy more shares, and if the price is high, they would buy fewer shares. This averaging out of the purchase price is what gives the strategy its name.
<br/><br/>
The benefit of dollar-cost averaging is that it helps to reduce the impact of market volatility on the investment. Instead of trying to time the market and make purchases when prices are low, investors using DCA systematically invest in the market over time. 
<br/><br/>
This strategy can help to smooth out the peaks and valleys of the market, which can reduce the overall risk of investing. By investing regularly, investors can take advantage of the power of compounding, which can increase their returns over time.
