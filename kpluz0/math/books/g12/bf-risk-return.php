The Sharpe ratio is calculated by subtracting the risk-free rate of return from the expected rate of return of the investment, and then dividing the result by the standard deviation of the investment's returns. The formula can be expressed as:
<br/><br/>
$vio Sharpe Ratio = (Expected return - Risk-free rate) / std deviation of returns$black
