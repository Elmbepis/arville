<br/><br/>
Risk refers to the probability of loss or uncertainty associated with an investment, which is the chance that an investment may not perform as expected or may result in a loss of principal.
<br/><br/>
The degree of risk associated with an investment depends on various factors, including the type of asset, market conditions, economic trends, and political events. 
