Systematic and<br/>Unsystematic Risk
@nblue
<br/><br/>
In investing, risk can be divided into two categories: systematic risk and unsystematic risk. 
<br/><br/>$vio<u> 
Systematic Risk
</u>$black<br/><br/>
Systematic risk is an important concept in investing that every investor should understand. It refers to the risk that is inherent in the overall market or economy and cannot be eliminated through diversification. 
Examples of systematic risk include inflation, recession, and political instability.
<br/><br/>
Systematic risk is also known as market risk and it affects the entire market or economy, rather than just a specific company or industry. 
This type of risk is beyond the control of investors and cannot be diversified away by investing in a range of different assets or securities. 
<br/><br/>
Systematic risk is a result of macroeconomic factors such as changes in interest rates, economic growth, and global events, which can affect the prices of all investments in the market.
<br/><br/>
Investors must be aware that the value of their investments may decline due to factors beyond their control, such as a recession or a global pandemic. 
To manage systematic risk, investors can use strategies such as diversification, which involves investing in a range of different assets that are not highly correlated with each other.
<br/><br/>$vio<u> 
Unsystematic Risk
</u>$black<br/><br/>
Unsystematic risk, also known as idiosyncratic risk, is the risk that is specific to a particular company or industry and can be reduced through diversification. 
It is the opposite of systematic risk, which affects the entire market or economy and cannot be eliminated through diversification.
<br/><br/>
Examples of unsystematic risk include changes in management, product recalls, lawsuits, and other company-specific events that can affect the value of the company's stock or bonds. 
For example, a company that relies heavily on a single product or customer is exposed to greater unsystematic risk than a company with a more diversified portfolio of products or customers.
<br/><br/>
To reduce unsystematic risk, investors can diversify their portfolio by investing in a range of different companies and industries. 
By spreading their investments across multiple companies and industries, investors can reduce their exposure to the specific risks of any one company or industry. 
