Outstanding reconciling items refer to transactions or items that appear on the bank statement but have not yet been recorded in the company's accounting records, or vice versa. 
<br/><br/>
These items are often the cause of differences or discrepancies between the bank statement and the company's accounting records, and they must be identified and reconciled in order to accurately balance the accounts. 
<br/><br/>
Below are some examples of reconciling items that need to be resolved if discrepancies are found in them.
