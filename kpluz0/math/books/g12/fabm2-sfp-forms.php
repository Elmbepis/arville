The statement of financial position (SFP), also known as the balance sheet, is one of the three primary financial statements that provide an overview of a company's financial health. 
The other two primary financial statements are the income statement and the cash flow statement. 
<br/><br/>
The SFP is a snapshot of a company's financial position at a specific point in time and provides information on the company's assets, liabilities, and equity.
<br/><br/>
There are two ways to present the information on the SFP: the report form and the account form. 
<br/><br/>
The report form is a more traditional format that lists assets on the left-hand side and liabilities and equity on the right-hand side. 
<br/><br/>
The account form, on the other hand, is a more modern format that presents the information in a more detailed and organized manner, by breaking down the assets and liabilities into subcategories.
