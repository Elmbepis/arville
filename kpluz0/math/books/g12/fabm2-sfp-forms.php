The assets are listed in order of liquidity, with cash listed first, followed by accounts receivable, and inventory. 
<br/><br/>
The liabilities are listed in order of maturity, with accounts payable listed first, followed by short-term loans and long-term loans. This format is easy to understand, as it presents the information in a clear and concise manner.
