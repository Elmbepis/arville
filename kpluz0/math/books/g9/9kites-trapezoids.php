<br/>
In geometry, a kite is a quadrilateral whose four sides can be grouped into two pairs of congruent sides that are adjacent to each other. 
In contrast, a parallelogram also has two pairs of congruent sides, but they are opposite to each other instead of being adjacent.
<br/><br/>
A rhombus (a quadrilateral with four sides of the same length) is a special type of a kite because it meets the requirement of having two pairs of congruent sides that are adjacent to each other. 
A square is a rhombus that has four right angles, and is therefore also a special case of a kite.
<br/><br/>
The angles between the congruent sides are called vertex angles. The other angles are called non-vertex angles. 
The non-vertex angles of a kite are congruent.
