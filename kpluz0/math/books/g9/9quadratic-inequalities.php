Solving a quadratic inequality is very similar to solving a quadratic equation. 
In fact, the first step is to solve the quadratic inequality as though it were an equation to obtain the two boundary points (not roots) of the inequality. 
<br/><br/>
The solution is then expressed as two inequalities involving the two boundary points, wherein each inequality satisfies the original inequality.
<br/><br/>
