A solid figure and its net have the same number of faces.
Also, their corresponding faces have the same size and shape.
If a net is folded into its corresponding solid figure, the edges of its adjacent faces must fit properly. 
<br/><br/>
Nets are useful when visualizing, measuring, or calculating the surface area of a solid figure. 
By adding up the areas of the faces of a net, we can get the total surface area of the solid figure.
