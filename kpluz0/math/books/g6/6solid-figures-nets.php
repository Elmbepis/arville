In the last lesson, we learned what solid figures are. 
In this lesson, we'll learn the concept of nets of solid figures.
<br/><br/>
In geometry, a net is a two-dimensional (2-D) shape that would form a solid figure if folded.
<br/><br/>
We may also say that a net is a 2-D shape that would be formed if a solid figure is cut open and laid flat to show its entire surface. 
