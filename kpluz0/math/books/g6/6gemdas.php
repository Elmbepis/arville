In math, the order in which operations are undertaken matters. 
Perfoming a set of operations in an incorrect order can result in errors in the calculation. 
<br/><br/>
For example, your answer to 2 + 3 x 5 will be 25 if you add 2 and 3 first before multiplying the result by 5. 
<br/><br/>
The correct order is to multiply 3 and 5 first before adding 2 to their product, which will give an answer of 30.  
<br/><br/>
The order in which math operations should be done from first to last is as follows:<br/> 
1. all operations inside groupings (G)<br/>
2. exponents (E)<br/>
3. multiplication and division (MD)<br/>
4. addition and subtraction (AS)
<br/><br/>
The letters shown in parentheses above form an acronym for us to remember the order of these operations more easily: GEMDAS. 
<br/><br/>
GEMDAS is also referred to as PEMDAS, wherein the 'P' stands for 'parenthesis', since groupings of operations are often enclosed by parentheses.
<br/><br/>
Lastly, when working on grouped operations (G), the rules of GEMDAS should also be applied.  
