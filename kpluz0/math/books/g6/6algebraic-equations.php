An equation is a statement of two expressions being equal. 
A verbal equation is an equation that uses verbal expressions to show this equality.
<br/><br/>
An algebraic equation, on the other hand, deals with the equality of algebraic expressions. 
Algebraic equations look like algebraic expressions, except that they contain an equality sign ('=').
<br/><br/>
In other words, a group of algebraic terms and operation symbols is not an equation unless it contains an equality symbol.
<br/><br/>
This is an example of a verbal equation:<br/>
$vio<b>The sum of twice a number and 5 is 275.</b>$black
<br/><br/>
The verbal equation above is equivalent to the algebraic equation below:<br/>
$vio<b>2x + 5 = 275</b>$black
<br/><br/>
Both equations state the same equality in different ways.
The first equation does it verbally, while the second one does it algebraically.
<br/><br/>
Here's another example of a verbal equation:<br/>
$vio<b>The difference between 24 and thrice a number equals the sum of the same number and 8.</b>$black
