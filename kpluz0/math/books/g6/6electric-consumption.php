Reading an Electric Meter
@nblue
<br/>
An electric energy meter is a device that measures the amount of electric energy that we consume at home.
Modern electric energy meters have digital read-outs that directly show energy consumption in real time.
<br/><br/>
In the Philippines, most households still use analog electric energy meters that use four or five dials to indicate energy consumption. 
We will learn how to read such meters in this lesson.
<br/><br/>
An analog energy meter is read from left to right.
Each of the dials of an energy meter points to a number from 0 to 9 and represents a digit in the number of kilowatt-hours consumed.  
<br/><br/>
For example, if the dials from left to right are pointing to the numbers 4, 7, 8, and 5, then the meter is showing 4,785 kWh.
