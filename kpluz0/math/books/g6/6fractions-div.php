<br/><br/>
Dividing fractions is very similar to multiplying fractions. 
In fact, it also involves fraction multiplication. 
<br/><br/>
To divide a fraction by another fraction, you simply need to multiply the first fraction (the dividend) by the reciprocal of the second fraction (the divisor). 
<br/><br/>
In other words, the numerator of the quotient is simply the product of the numerator of the dividend and the denominator of the divisor. 
The denominator of the quotient, on the other hand, is the product of the denominator of the dividend and the numerator of the divisor. 
<br/><br/>
You can't directly divide mixed fractions, so you need to change a mixed fraction into an improper fraction first before you can use it in fraction division.
<br/><br/>
Finally, you need to reduce your product in lowest terms to make it neater and simpler. 
<br/><br/>
