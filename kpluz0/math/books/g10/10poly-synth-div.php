Synthetic Division<br/>of Polynomials
@nblue
<br/>
When the long method is used to divide polynomials, the terms are rewritten several times.
This repetition can be eliminated by using synthetic division.
<br/><br/>
Synthetic division is a method for dividing polynomials conveniently.
In synthetic division, there is no need to write the variables and their exponents since the positions of the coefficients indicate their corresponding exponents, as long as the terms of the polynomial are written in descending order of power.
<br/><br/>
There are two differences between the steps of long division and those of synthetic division:
<br/><br/>
1. The divisor in synthetic division just consists of the constant, and is always based on the form $vio<i>x-c</i>$black. Thus, if the divisor in long division is x+7, then the divisor in synthetic division is -7. If it's x-4 in long division, then it's 4 in synthetic division. 
<br/><br/>
2. The subtraction operations involving the products of the terms of the dividend and the divisor are replaced with addition in synthetic division, to compensate for the negation of the constant in the divisor.
<br/><br/>
Here are the steps for synthetic division of polynomials:
<br/><br/>
$vio Step 1.$black Write the coefficients of the dividend in descending order of power to the right of the synthetic division symbol.  
<br/><br/>
$vio Step 2.$black Write the negative of the constant <i>c</i> of the divisor to the left of the division symbol. Thus, if the divisor is x+3, write -3.
<br/><br/>
$vio Step 3.$black Bring down the leading coefficient of the dividend to the bottom row under the horizontal bar.
<br/><br/>
$vio Step 4.$black Multiply <i>c</i> by the value just written on the bottom row. Write the product under the next coefficient of the dividend.
<br/><br/>
$vio Step 5.$black Add the product in step 4 and the dividend coefficent above it and write their sum in the bottom row under the horizontal bar.
<br/><br/>
$vio Step 6.$black Repeat steps 4 and 5 for all the remaining terms of the dividend.
<br/><br/>
$vio Step 7.$black Write out the answer.
