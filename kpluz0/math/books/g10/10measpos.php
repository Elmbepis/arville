A measure of position is a way of specifying a range wherein a certain percentage of the values in a set of data fall. 
In this lesson, we will learn three measures of position: percentiles, quartiles, and deciles.
<br/><br/><br/>
@blue
Percentiles
@nblue
<br/>
If the values in a set of data are arranged from lowest to greatest and then divided into 100 smaller groups containing the same number of values, then each of these groups is called a percentile.
<br/><br/>
Consider a data set that contains 500 values.  Each percentile of this data set would then contain 5 values.
<br/><br/>
The pth percentile of a data set refers to the value such that p% of the data are below this value and (100 - p)% of the values are at or above it.
For example, if your score in a certain test is in the 90th percentile, then that means you scored better than 90% of people who took the same test.
<br/><br/>
Recall that the median of a data set is the value that is in the middle of all the values of that data set. Thus, the median is the 50th percentile.
<br/><br/><br/>
@blue
Quartiles
@nblue
<br/>
If the values in a set of data are arranged from lowest to greatest and then divided into 4 equal groups, then each of these groups is called a quartile.
<br/><br/>
Each quartile therefore contains 25% of the values of the data set.
<br/><br/>
