<br/><br/>
The first quartile, denoted by Q1, is the 25th percentile of the data set. Thus, Q1 refers to the lowest 25% of the ordered data.
<br/><br/>
The term 'first quartile' also refers to the value itself below which 25% of the ordered data lie.
One may consider this Q1 value to be the median of the lower half of the data.
<br/><br/>
