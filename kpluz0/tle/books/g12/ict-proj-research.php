Demographic Research
@nblue
<br/><br/>
Demographic research is an essential component of ICT project planning, as it helps project planners to understand the basic characteristics of the target audience. 
<br/><br/>
Demographic research focuses on identifying and describing the demographic characteristics of a population, such as age, gender, income, education level, and geographic location. 
