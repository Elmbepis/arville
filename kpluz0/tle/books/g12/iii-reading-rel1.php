<br/><br/>
A citation is a reference to the source of information used in your research. Citing related literature is an important aspect of academic writing, as it allows researchers to acknowledge the work of others and avoid plagiarism. 
<br/><br/>
There are several standard citation styles that are widely used in academic writing, such as APA, MLA, and Chicago Manual of Style. Each citation style has its own set of rules and guidelines for formatting citations and references.
<br/><br/>$vio<u>
APA (American<br/>Psychological Association)
</u>$black<br/><br/>
The APA (American Psychological Association) citation style is a set of guidelines for formatting and citing sources in academic writing. It is widely used in the social sciences, such as psychology, sociology, and education.
<br/><br/>
In APA style, in-text citations are used to give credit to sources used in the text of a paper, and a corresponding reference list is included at the end of the paper to provide detailed information about each source cited.
<br/><br/>
In-text citations typically include the author's last name and the publication year in parentheses, such as (Smith, 2020). If a direct quote is used, the page number should also be included, such as (Smith, 2020, p. 25).
<br/><br/>
The reference list is arranged alphabetically by author's last name and includes the full citation information for each source, such as the author's name, publication date, title of the work, and publication information.
<br/><br/>
The standard format is as follows:
<br/><br/>
Author's last name, first initial. (Publication year). Title of the work. Location: Publisher.
<br/><br/>
There are specific guidelines for citing different types of sources, such as books, journal articles, and websites, as well as special formatting rules for tables, figures, and other types of content. 
