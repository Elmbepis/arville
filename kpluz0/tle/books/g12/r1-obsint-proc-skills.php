1.	Participant Observation
<br/><br/>
</u>$black
This method involves the researcher becoming a part of the group or setting being studied in order to gain a more in-depth understanding of the participants and their behaviors. 
<br/><br/>
The aim of this method is to gain a firsthand understanding of the social phenomena under investigation by actively participating in the daily activities of the group or setting. 
<br/><br/>
This method involves the researcher observing and documenting the behaviors, attitudes, and interactions of the participants in their natural environment. 
The researcher's observations may be recorded through field notes, audio or video recordings, or photographs. 
<br/><br/>
Participant observation is commonly used in anthropology, sociology, and other social sciences to study cultural practices, social norms, and group dynamics.
<br/><br/>
