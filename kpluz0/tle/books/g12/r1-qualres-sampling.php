Convenience sampling is the most basic and common sampling procedure used in qualitative research. It involves selecting participants or data sources that are easily accessible or available to the researcher. 
This type of sampling is often used when time or resources are limited. 
<br/><br/>
An example of convenience sampling in qualitative research could be a researcher who wants to study the attitudes of people towards a new policy introduced in a particular city. 
The researcher might stand at a busy intersection in the city and randomly select individuals passing by to participate in a brief interview about their views on the policy. 
<br/><br/>
This approach would be convenient for the researcher and may yield useful information, but it may not be representative of the wider population's views on the policy.
