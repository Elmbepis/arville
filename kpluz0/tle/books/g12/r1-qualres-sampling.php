<br/><br/>
</u>$black
Snowball sampling is often used when studying hard-to-reach populations or when the population size is unknown. 
It involves recruiting participants through referrals from existing participants. 
<br/><br/>
An example of snowball sampling might be a researcher studying the experiences of individuals living with a rare disease. They could reach out to the patient they know and ask them to refer other patients they might know.
