One example of an ICT project for social change is the Grameenphone Community Information Centers (CICs) in Bangladesh. 
Grameenphone is the leading telecommunications company in Bangladesh and has been providing ICT services to rural communities through a network of Community Information Centers (CICs). 
<br/><br/>
These centers provide internet access, computer training, and other ICT services to rural communities, with a focus on improving access to education, healthcare, and financial services.
<br/><br/>
The project aims to bridge the digital divide between urban and rural areas by providing access to ICT to remote communities. 
This helps to promote education, improve healthcare outcomes and empower people to take control of their financial future. 
<br/><br/>
The project is designed to be sustainable and self-sufficient, with the centers generating revenue through the sale of ICT services, and the local communities are trained to manage and operate the centers.
<br/><br/>
One of the most significant impact of the project has been on education. With the help of CICs, students in rural areas have been able to access online educational resources, which have helped to improve their academic performance. 
<br/><br/>
In addition, CICs have also provided access to information on health and agriculture, which has helped to improve health outcomes and increase agricultural productivity in the communities.
<br/><br/>
The Grameenphone Community Information Centers is an example of an ICT project for social change that effectively utilizes technology to bridge the digital divide and promote positive change in a community. 
 
