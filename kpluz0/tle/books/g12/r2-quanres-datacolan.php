</u>$black<br/><br/>
Observations are a method of data collection used in quantitative research, which involves systematically observing and recording behaviors or events. 
<br/><br/>
Observations can be conducted in a natural setting or in a laboratory, and can be either participant observations, where the researcher is actively involved in the activity being observed, or non-participant observations, where the researcher is not involved.
<br/><br/>
In naturalistic observation, the researcher observes the participants in their natural setting, without any intervention or manipulation of variables. 
<br/><br/>
This method is useful when the researcher wants to study behavior in a natural setting without interference from the researcher or other variables. For example, a researcher may want to observe how people interact in a coffee shop.
<br/><br/>
In structured observation, the researcher designs a situation or scenario in which to observe behavior. 
<br/><br/>
