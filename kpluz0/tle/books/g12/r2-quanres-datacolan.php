1.2 Variability
</i>$black<br/><br/>
Variability refers to the spread or dispersion of the data and can be measured using various statistical measures such as the range, variance, and standard deviation. 
<br/><br/>
The range is the difference between the maximum and minimum values in the data set. 
<br/><br/>
The variance is the average of the squared differences between each value and the mean of the data set. The standard deviation is the square root of the variance and is a measure of the spread of the data around the mean.
