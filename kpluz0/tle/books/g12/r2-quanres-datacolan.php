<br/><br/>
Surveys typically involve a structured questionnaire that contains a set of predetermined questions, which can be administered through various mediums, including paper-based forms, online surveys, telephone interviews, or face-to-face interviews.
<br/><br/>
Surveys are a popular method for collecting quantitative data because they can be used to collect large amounts of data from a diverse group of individuals in a relatively short amount of time. 
Surveys can be conducted in a variety of ways, including through paper and pencil, phone, email, or online.
<br/><br/>
To create an effective survey, researchers should first identify the research question or objective and then develop a set of questions that are clear, concise, and relevant to the research question. 
