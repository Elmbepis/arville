Sole Proprietorship
@nblue
<br/><br/>
A sole proprietorship is an unincorporated business owned and run by a single individual, also known as the proprietor. 
This means that the business and the owner are legally considered the same entity, and the owner has complete control over all aspects of the business.
<br/><br/>
In terms of financial reporting and the SCI, a sole proprietorship reports its financial information on a single tax return filed by the owner. The owner's personal tax return includes the business's net income or loss, as well as any taxes owed.
<br/><br/>
As for changes in equity, a sole proprietorship may have transactions with the owner that affect equity, such as investments made by the owner, drawings taken by the owner, or the owner's personal use of business assets. 
These transactions would be recorded in the equity section of the balance sheet.
<br/><br/>
While a sole proprietorship is easy and inexpensive to set up and maintain, it also comes with significant risks for the owner. 
As mentioned earlier, the owner is personally liable for all debts and liabilities of the business, which means that personal assets could be at risk if the business incurs significant debts or is sued.
<br/><br/>
In terms of SCE, a sole proprietorship does not have any stockholders, so there will be no changes in equity due to stock issuances or buybacks. 
However, there may be changes in equity due to net income or loss, as well as changes in equity due to transactions with owners.
