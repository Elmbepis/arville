Partnership
@nblue
<br/><br/>
A partnership is a type of business organization in which two or more individuals come together to own and operate the business. Partnerships can take on various forms, including general partnerships, limited partnerships, and limited liability partnerships.
<br/><br/>
In a general partnership, all partners are equally responsible for the debts and liabilities of the business. This means that each partner is personally liable for any obligations or debts incurred by the business, 
and their personal assets may be at risk if the business is unable to meet its obligations.
<br/><br/>
In a limited partnership, there are two types of partners: general partners and limited partners. General partners are responsible for managing the business and are personally liable for its debts and obligations. 
Limited partners, on the other hand, are only liable for the amount of money they have invested in the business and do not participate in managing the business.
<br/><br/>
In a limited liability partnership, all partners have limited liability protection. This means that they are only responsible for their own actions and are not personally liable for the actions of other partners.
<br/><br/>
In terms of financial reporting and the SCI, partnerships are required to file a tax return that reports the partnership's income, deductions, and credits. However, the partnership itself is not taxed on its income. 
Instead, each partner reports their share of the partnership's income or loss on their personal tax return.
<br/><br/>
In terms of equity, a partnership does not have stockholders, so there are no changes in equity due to stock issuances or buybacks. However, there may be changes in equity due to net income or loss, as well as changes in equity due to transactions with partners.
<br/><br/>
These transactions may include capital contributions made by partners, withdrawals or distributions taken by partners, or changes in ownership due to the admission or withdrawal of partners.
<br/><br/>
Partnerships come with certain advantages, such as shared management and control, shared risk and liability, and potential tax benefits. 
However, partnerships also require careful planning and communication among partners to ensure that all parties are on the same page and that the business runs smoothly.
