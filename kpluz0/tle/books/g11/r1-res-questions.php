<br/><br/>
</u>$black
A descriptive research question is a type of research question that seeks to describe a particular phenomenon, situation, or relationship. 
This type of question is concerned with collecting data that provides a detailed and accurate picture of the subject under investigation.
<br/><br/>
Descriptive research questions do not aim to establish a cause-and-effect relationship between variables, but rather to provide a thorough and systematic description of the characteristics of the phenomenon or situation being studied. 
They typically begin with 'What is...' or 'How many...'. 
<br/><br/>
$pink<i>Example:</i>$black 'What is the prevalence of obesity among adults in the United States?'
<br/><br/>
$vio<u>
