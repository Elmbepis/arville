<br/><br/>
</u>$black
An exploratory research question is a type of research question that aims to explore a particular phenomenon, situation, or relationship. 
This type of question is used when the researcher has limited knowledge or understanding of the topic and wants to gain a better understanding of it. 
<br/><br/>
