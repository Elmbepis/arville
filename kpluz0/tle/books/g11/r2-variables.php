<br/><br/>
Control variables are important because they help to ensure that any observed effects of the independent variable on the dependent variable are not due to the influence of other variables. 
<br/><br/>
For example, in the above example, the researcher may control for factors such as diet, age, and gender, to ensure that the observed effects of exercise on weight loss are not due to these variables.
