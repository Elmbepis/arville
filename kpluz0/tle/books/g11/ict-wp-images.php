Avoiding<br/>Copyright Issues
@nblue
<br/><br/>
When integrating external material, such as images and other media, into a word processor document, it's important to consider copyright and intellectual property laws. 
This means that you should only use images, audio and video that you have created yourself or that you have obtained the rights to use. 
<br/><br/>
Many images and other types of media found online may be protected by copyright and may not be used without the permission of the copyright holder.
<br/><br/>
To avoid copyright issues, you can use free stock images, videos and audio available in the internet, or take a picture or create a video yourself. 
It's also important to give credit to the original author when using copyrighted material and to include a link to the source.
<br/><br/>
Keeping track of the sources of external materials that you use in your document is a good idea in case you need to verify the rights at a later date.
