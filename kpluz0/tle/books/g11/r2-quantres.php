2. Correlational Research
</u>$black<br/><br/>
Correlational research is a type of research that focuses on identifying and measuring the relationship between two or more variables. 
The main objective of correlational research is to determine whether there is a relationship between variables, the strength of that relationship, and the direction of the relationship.
<br/><br/>
Correlational research is often used in social sciences, psychology, and education to investigate the relationship between variables that cannot be manipulated or controlled. 
For example, researchers may use correlational research to study the relationship between socioeconomic status and academic achievement.
<br/><br/>
Correlational research can be conducted through various methods, such as surveys, questionnaires, and observations. Researchers can also use existing data sets to conduct correlational research.
<br/><br/>
