Non-Experimental<br/>Research
@nblue
<br/><br/>
Non-experimental research is a type of research design that does not involve manipulating variables. Instead, it aims to describe or observe a particular phenomenon, behavior, 
or relationship between variables through the collection and analysis of numerical data. 
<br/><br/>
Non-experimental research is often used in social and behavioral sciences, education, and public health.
<br/><br/>
Non-experimental research can be further classified into two types: descriptive and correlational research.
<br/><br/>$vio<u> 
1. Descriptive Research
</u>$black<br/><br/>
Descriptive research is a type of research design that aims to observe and describe a particular phenomenon or behavior. 
This type of research is particularly useful when the researcher wants to gain an understanding of the current situation, characteristics, and behavior of a group or population. 
<br/><br/>
Descriptive research is used in various fields, including psychology, sociology, education, and marketing.
<br/><br/>
In descriptive research, the researcher does not manipulate any variables but instead observes and measures them. This approach allows the researcher to collect data in a non-intrusive way, making it easier to study complex and sensitive topics. 
The researcher typically uses surveys, questionnaires, interviews, or observation to collect data.
<br/><br/>
Surveys and questionnaires are the most commonly used methods in descriptive research. A survey is a structured set of questions that are given to a sample of people. The questions are designed to gather information about people's beliefs, opinions, and behaviors. 
Questionnaires are similar to surveys but are usually self-administered by the respondents.
<br/><br/>
Interviews are another method used in descriptive research. In an interview, the researcher asks open-ended questions to the participants to gain an in-depth understanding of their experiences, attitudes, and opinions. 
Interviews can be conducted in person, over the phone, or online.
<br/><br/>
Observation is also used in descriptive research. In this method, the researcher observes the behavior of the participants in a natural or controlled setting. The researcher notes down their observations and analyzes the data collected.
<br/><br/>
The results of descriptive research are often presented in tables, graphs, and charts. These visual representations make it easier to interpret and communicate the data. 
Descriptive research can be used as a preliminary step in research to gain insights and develop hypotheses for further investigation.
