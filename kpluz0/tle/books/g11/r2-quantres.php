The coefficient ranges from -1.0 to +1.0, where -1.0 indicates a perfect negative correlation, +1.0 indicates a perfect positive correlation, and 0 indicates no correlation.
<br/><br/>
A scatterplot is a graph that displays the relationship between two variables. The x-axis represents one variable, while the y-axis represents the other variable. 
The data points on the scatterplot represent the values of the two variables for each individual in the study. A scatterplot can indicate the strength and direction of the relationship between variables.
<br/><br/>
Note that correlational research cannot establish causality, meaning it cannot determine if one variable causes another. However, it can provide valuable information about the relationship between variables and help generate hypotheses for further research.
