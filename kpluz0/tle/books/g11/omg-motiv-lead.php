Management is the process of planning, organizing, directing, and controlling resources (such as human, financial, and material) to achieve organizational goals efficiently and effectively. It involves coordinating and overseeing activities, 
tasks, and people within an organization to ensure that resources are used optimally to accomplish objectives. 
<br/><br/>
