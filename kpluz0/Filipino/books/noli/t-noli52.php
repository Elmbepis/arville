											ikalimang&nbsp;<i>karta</i>&nbsp;ay lumabas 
											ang isang alas.</font></p>
											<p align="justify" style="margin-left: 80px; margin-right: 80px">
											<font face="Arial" color="#333333" style="font-size: 13pt">
											<font face="Arial" color="#333333">
