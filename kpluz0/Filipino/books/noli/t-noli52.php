											<font face="Arial" color="#333333">
											Nang makaraan ang ilang minuto'y 
											tumugtog ang a las ocho sa relos ng 
											simbahan, at ipinahayag ng kampana 
											ang oras ng mga kaluluwa; nguni't 
											hindi inanyayahan ni Lucas 
											makipagsugal sa kanya ang sino man, 
