											idinugtong;--ngayo'y pabayaan po 
											ninyong ako'y mag-isang humanap ng 
											pagkabuhay.</font></p>
											<p align="justify" style="margin-left: 80px; margin-right: 80px">
											<font face="Arial" color="#333333" style="font-size: 13pt">
											<font face="Arial" color="#333333">
											Umalis si Elias na hindi nagsabi ng 
											kataga man lamang, at nawala sa 
											gitna ng kadiliman.</font></p>
											<p align="justify" style="margin-left: 80px; margin-right: 80px">
