sa kasamahan ng mga intsik. Mabuti pa ang malunod kay sa mapasama sa mga intsik--ang wika 
ko--at siya'y iniabsang ko sa tubig!</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Inilagay ni Ibarra ang kanyang mga kamay 
sa magkabilang balikat ng maglilibing at mahabang oras na siya'y tinitigan ng 
tinging hindi maisaysay kung anong ibig sabihin.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">--Ikaw ay wala kung 
di isang kulang palad!--ang sinabi, at umalis na dalidaling tinatahak ang mga buto, mga hukay, 
mga kruz, na parang isang sira ang isip.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Hinahaplos ng maglilibing ang kanyang 
bisig at bumubulong:</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">--Ang ginagawang mga kaligaligan ng mga patay! Binugbog ako 
ng baston ng paring malaki, dahilang ipinahintulot kong ilibing ang patay na iyon ng ako'y may sakit; ngayo'y 
kaunti ng baliin 
nito ang aking bisig, dahil sa pagkahukay ko ng bangkay. Ito nga namang mga kastila! 
Marahil pa'y alisan ako nito ng aking hanap-buhay!</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Matulin ang lakad ni Ibarra na sa malayo 
ang tanaw; sumusunod sa kanyang umiiyak ang alilang matandang lalaki.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Lulubog na lamang ang araw; makakapal na 
mga dilim ang siyang lumalatag sa Kasilanganan; isang hanging mainit ang 
siyang nagpapagalaw sa dulo ng mga kahoy at nagpaparaing sa mga kawayanan.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Nakapugay na lumalakad si Ibarra; sa 
kanyang mga mata'y walang bumabalong na isang luha man lamang, walang tumatakas 
sa kanyang dibdib kahi't isang buntong hininga. Lumalakad na parang may 
pinagtatanauan, marahil sa pagtakas sa anino ng 
kanyang ama, o baka naman kaya sa dumadating na unos. Tinahak ang baya't lumabas 
sa luwal, tinungo yaong lumang bahay na malaon ng panahong hindi 
tinutungtungan. </font></p>
											<p align="justify" style="margin-left: 80px; margin-right: 80px">
											<font face="Arial" color="#333333" style="font-size: 13pt">Naliligid ang bahay na iyon ng pader na sinisibulan ng mga 
damong makakapal ang dahon, tila mandin siya'y hinuhudyatan; bukas ang mga 
bintana; umuugoy ang ilang-ilang at ipinapagaspas ng&nbsp; buong&nbsp; kasayahan ang 
kanyang mga sangang hitik ng mga kalapati na nagpapaligidligid sa matibong 
na bubong ng kanilang tahanang na sa gitna ng halamanan.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Nguni't hindi pinapansin ng binata ang kaligayahang itong inihahandog 
sa kanyang pagbalik sa lumang bahay: nakapako ang 
kanyang mga mata sa anyo ng isang sacerdoteng kanyang makakasalubong. Ito'y 
ang kura sa San Diego, yaong laging nagdidilidiling frankiskano na ating 
nakita, ang kaaway ng alperes. Tinitiklop ng hangin ang kanyang malapad na 
sombrero; ang kanyang habitong ginggo'y dumirikit sa kanyang katawan at 
ipinakikita ang anyo nito; na ano pa't namamasid ang kanyang mga payat na 
hitang may pagka sakang. Sa kana'y may hawak na isang bastong palasang may 
tampok na garing. Noon lamang nagkakita silang dalawa ni Ibarra.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Pagsasalubong nila'y sandaling huminto ang 
binata't siya'y tinitigan; iniiwas ni Padre Salvi ang kanyang mga mata at 
nagpakonowaring nalilibang.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Sandalingsandali lamang tumagal ang 
pag-aalinlangan: maliksing linapitan siya ni Ibarra, pinatigil at idiniin ng&nbsp; 
buong&nbsp; lakas ng kanyang kamay na ipinatong sa balikat ng pari, at nagsalitang 
halos bahagya na mawatasan:</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">--Ano ang ginawa mo sa aking ama?--ang 
itinanong.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Si Padre Salving namutla, at nangatal ng 
mabasa niya ang mga damdaming nalalarawan sa mukha ng binata'y hindi 
nakasagot; nawalan ng diwa.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">--Ano ang ginawa mo sa aking ama?--ang 
muling itinanong na nalulunod ang boses.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Ang sacerdoteng untiunting nahutok, dahil 
sa kamay na sa kanya'y nagdiriin ay nagpumilit at sumagot:</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">--Kayo po'y nagkakamali; wala akong 
ginagawang ano man sa inyong ama.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">--Anong wala?--ang ipinagpatuloy ng 
binata, at saka siya idiniin hanggang sa siya'y mapaluhod.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">--Hindi po, sinasabi ko sa inyo ang 
katotohanan! ang aking hinalinhan, si Padre Damaso ang may kagagawan....</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">--Ah!--ang sinabi ng binata't siya'y 
binitiwan at bago tumampal sa noo. At iniwan ang abang si Padre Salvi at 
dalidaling tinungo ang kanyang sariling bahay.</font></p>
<p align="justify" style="margin-left: 80px; margin-right: 80px">
<font face="Arial" color="#333333" style="font-size: 13pt">Samantala'y dumating ang alila at 
tinulungan sa pagtindig ang prayle.</font></p>
