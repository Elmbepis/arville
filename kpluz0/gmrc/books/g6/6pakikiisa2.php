b. Naipaliliwanag na ang Pakikipagbayanihan ng Pamilya ay Pagpapakita ng Bolunterismo ng Mag-anak

Ang bolunterismo ay hindi isang bagay na ginagawa lamang ng mga organisasyon o ng mga taong maraming oras - ito ay isang pagpapahayag ng pananampalataya na ang bawat maliit na tulong ay may halaga. Kapag ang isang pamilya ay sama-samang nagboboluntaryo, sila ay nagiging higit pa sa isang grupo ng mga indibidwal - sila ay nagiging isang puwersa ng kabutihan na ang pinagsamang lakas ay mas malaki kaysa sa kabuuan ng mga bahagi nito. Ang ganitong uri ng kolektibong pagkilos ay nagpapakita na ang bolunterismo ay hindi isang indibidwal na sakripisyo kundi isang pampamilyang selebrasyon ng kakayahang magbigay.

